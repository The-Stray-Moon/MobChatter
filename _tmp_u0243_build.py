def clamp(x):
    return max(0, min(4, x))

def extra(w):
    return clamp(int(math.floor(10 * (w - 1) + 0.5)))

def build(batch):
    plan = json.load(open("data/dialogue/unique_plan.json", encoding="utf-8"))[batch]
    data = {m["mob_id"]: m for m in plan}
    content = {
        "pixelmon:lillipup": LILLIPUP,
        "pixelmon:linoone": LINOONE,
        "pixelmon:litleo": LITLEO,
        "pixelmon:litten": LITTEN,
    }
    mobs = []
    total = 0
    errs = []
    for mob_id, src in content.items():
        w = data[mob_id]["weights"]
        scen = {}
        for key in ("walk", "idle", "look_player", "tempted", "collide", "mate", "pickup",
                    "target_acquire", "targeting", "melee_attack", "spawn"):
            want = 10 + extra(w[key])
            items = n(want - 10, src[key])
            scen[key] = items
            total += len(items)
        scen["hurt"] = src["hurt"]
        total += 19
        mobs.append({"mob_id": mob_id, "scenarios": scen})
    # validate lengths
    for mob in mobs:
        for key, arr in mob["scenarios"].items():
            if key == "hurt":
                for sub, lst in arr.items():
                    chk(mob["mob_id"], key + "." + sub, lst, errs)
            else:
                chk(mob["mob_id"], key, arr, errs)
    return {"batch": batch, "mobs": mobs}, total, errs

def chk(mob_id, key, arr, errs):
    for it in arr:
        zl = len(it["zh"])
        el = len(it["en"].split())
        if zl < 6 or zl > 20:
            errs.append((mob_id, key, "zh", zl, it["zh"]))
        if el < 4 or el > 14:
            errs.append((mob_id, key, "en", el, it["en"]))

