mobs = [
 ("pixelmon:cufant", cufant),
 ("pixelmon:cursola", cursola),
 ("pixelmon:cutiefly", cutiefly),
 ("pixelmon:cyclizar", cyclizar),
]

SCEN = ["walk", "idle", "look_player", "tempted", "collide", "mate",
        "pickup", "target_acquire", "targeting", "melee_attack", "spawn"]
HURT = ["generic", "fire", "fall", "drown", "explosion", "projectile",
        "magic", "starvation", "lightning", "void"]

plan = json.load(open("data/dialogue/unique_plan.json", encoding="utf-8"))["u0167"]
weights = {p["mob_id"]: p["weights"] for p in plan}

def need(w):
    return 10 + max(0, min(4, round(10 * (w - 1))))

problems = []
all_zh, all_en = {}, {}
out = {"batch": "u0167", "mobs": []}
total = 0
for mob_id, data in mobs:
    w = weights[mob_id]
    scen = {}
    for s in SCEN:
        pairs = data[s]
        want = need(w[s])
        if len(pairs) != want:
            problems.append(f"{mob_id} {s}: {len(pairs)} != {want}")
        scen[s] = [S(z, e) for z, e in pairs]
        total += len(pairs)
    hurt = {}
    for h in HURT:
        pairs = data["hurt"][h]
        want = 10 if h == "generic" else 1
        if len(pairs) != want:
            problems.append(f"{mob_id} hurt.{h}: {len(pairs)} != {want}")
        hurt[h] = [S(z, e) for z, e in pairs]
        total += len(pairs)
    scen["hurt"] = hurt

    # length + duplicates
    seen_zh, seen_en = {}, {}
    for s in SCEN:
        for it in scen[s]:
            zh, en = it["zh"], it["en"]
            if not (6 <= len(zh) <= 20):
                problems.append(f"{mob_id} {s} zh len {len(zh)}: {zh}")
            wc = len(en.split())
            if not (4 <= wc <= 14):
                problems.append(f"{mob_id} {s} en words {wc}: {en}")
            if zh in seen_zh:
                problems.append(f"{mob_id} dup zh: {zh}")
            if en in seen_en:
                problems.append(f"{mob_id} dup en: {en}")
            seen_zh[zh] = 1
            seen_en[en] = 1
            if zh in all_zh:
                problems.append(f"CROSS dup zh {mob_id} vs {all_zh[zh]}: {zh}")
            if en in all_en:
                problems.append(f"CROSS dup en {mob_id} vs {all_en[en]}: {en}")
            all_zh[zh] = mob_id
            all_en[en] = mob_id
    out["mobs"].append({"mob_id": mob_id, "scenarios": scen})

print("total:", total)
print("problems:", len(problems))
for p in problems:
    print(" -", p)

if not problems:
    os.makedirs("data/dialogue/unique", exist_ok=True)
    with open("data/dialogue/unique/u0167.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("written")
