import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PLAN = json.loads((ROOT / "data/dialogue/unique_plan.json").read_text(encoding="utf-8"))["u0311"]

SCEN = ["walk", "idle", "look_player", "tempted", "collide", "mate", "pickup",
        "target_acquire", "targeting", "melee_attack", "spawn"]
DAMAGE = ["fire", "fall", "drown", "explosion", "projectile", "magic",
          "starvation", "lightning", "void"]


def pairs(rows):
    out = []
    for row in rows:
        zh, en = row
        out.append({"zh": zh.strip(), "en": en.strip()})
    return out


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def extra(weight):
    return clamp(int(round(10 * (weight - 1))), 0, 4)


def build(mob_id, scenario_lines, damage_lines):
    info = next(m for m in PLAN if m["mob_id"] == mob_id)
    w = info["weights"]
    scen = {}
    for key in SCEN:
        base = scenario_lines[key]
        need = 10 + extra(w[key])
        assert len(base) >= need, (mob_id, key, len(base), need)
        scen[key] = pairs(base[:need])
    hurt = {"generic": pairs(scenario_lines["hurt.generic"][: 10 + extra(w["hurt"])])}
    for d in DAMAGE:
        lines = damage_lines[d]
        assert len(lines) == 1
        hurt[d] = pairs(lines)
    scen["hurt"] = hurt
    return {"mob_id": mob_id, "scenarios": scen}


