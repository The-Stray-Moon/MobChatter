assert len(plan) == 4

errors = []
def zh_ok(s):
    n = len(s)
    return 6 <= n <= 20
def en_ok(s):
    w = len(s.split())
    return 4 <= w <= 14

out = {"batch": "u0284", "mobs": []}
allzh = {}
for mob in plan:
    mid = mob["mob_id"]
    src = D[mid]
    scen = OrderedDict()
    total = 0
    for name in ORDER:
        w = weights[mid][name]
        cnt = 10 + max(0, min(4, round(10 * (w - 1))))
        if name == "hurt":
            gen = src["hurt"]["generic"]
            if not (len(gen) >= cnt):
                errors.append((mid, name, "short %d<%d" % (len(gen), cnt)))
            payload = {"generic": [{"zh": z, "en": e} for z, e in gen[:cnt]]}
            for d in DMG:
                payload[d] = [{"zh": z, "en": e} for z, e in src["hurt"][d]]
            scen["hurt"] = payload
        else:
            lines = src[name]
            if not (len(lines) >= cnt):
                errors.append((mid, name, "short %d<%d" % (len(lines), cnt)))
            scen[name] = [{"zh": z, "en": e} for z, e in lines[:cnt]]
    for name, payload in scen.items():
        groups = [("generic", payload["generic"])] if name == "hurt" else [(name, payload)]
        if name == "hurt":
            groups += [(d, payload[d]) for d in DMG]
        for key, lines in groups:
            for ln in lines:
                if not zh_ok(ln["zh"]):
                    errors.append((mid, key, "zh len %d: %s" % (len(ln["zh"]), ln["zh"])))
                if not en_ok(ln["en"]):
                    errors.append((mid, key, "en words %d: %s" % (len(ln["en"].split()), ln["en"])))
                allzh.setdefault(ln["zh"], []).append(mid)
    out["mobs"].append({"mob_id": mid, "scenarios": scen})

