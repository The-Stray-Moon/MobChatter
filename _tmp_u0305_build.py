SCEN = ["walk", "idle", "look_player", "tempted", "collide", "mate", "pickup",
        "target_acquire", "targeting", "melee_attack", "spawn"]
HURT = ["generic", "fire", "fall", "drown", "explosion", "projectile", "magic",
        "starvation", "lightning", "void"]
W = {"walk": 1.2, "idle": 1.4, "look_player": 1.4, "tempted": 1.0, "collide": 0.8,
     "mate": 0.8, "pickup": 0.2, "target_acquire": 1.0, "targeting": 1.0,
     "melee_attack": 1.0, "spawn": 1.2}


def want(key):
    return 10 + max(0, min(4, round(10 * (W[key] - 1))))


out = {"batch": "u0305", "mobs": []}
problems = []
for mid, sc in mobs:
    m = {"mob_id": mid, "scenarios": {}}
    for k in SCEN:
        m["scenarios"][k] = sc[k]
        exp = want(k)
        if len(sc[k]) != exp:
            problems.append(f"{mid}/{k}: {len(sc[k])} != {exp}")
    m["scenarios"]["hurt"] = {}
    for k in HURT:
        m["scenarios"]["hurt"][k] = sc["hurt"][k]
        exp = 10 if k == "generic" else 1
        if len(sc["hurt"][k]) != exp:
            problems.append(f"{mid}/hurt.{k}: {len(sc['hurt'][k])} != {exp}")
    out["mobs"].append(m)

allzh, allen = Counter(), Counter()
for mid, sc in mobs:
    sents = []
    for k in SCEN:
        sents += sc[k]
    for k in HURT:
        sents += sc["hurt"][k]
    for s in sents:
        z, e = s["zh"], s["en"]
        if not (6 <= len(z) <= 20):
            problems.append(f"zh len {len(z)}: {z}")
        wc = len(e.split())
        if not (4 <= wc <= 14):
            problems.append(f"en words {wc}: {e}")
        allzh[z] += 1
        allen[e] += 1
problems += ["DUP: " + x for x, c in allzh.items() if c > 1]
problems += ["DUP: " + x for x, c in allen.items() if c > 1]

print("problems:", len(problems))
for p in problems:
    print(" -", p)
if problems:
    sys.exit(1)

