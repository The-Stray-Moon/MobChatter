SCEN = ["walk", "idle", "look_player", "tempted", "collide", "mate", "pickup",
        "target_acquire", "targeting", "melee_attack", "spawn"]
DMG = ["generic", "fire", "fall", "drown", "explosion", "projectile", "magic",
       "starvation", "lightning", "void"]


def extra(w):
    return max(0, min(4, int(round(10 * (w - 1)))))


def build():
    mobs = []
    errors = []
    for info in PLAN:
        mid = info["mob_id"]
        src = R[mid]
        sc = {}
        for name in SCEN:
            need = 10 + extra(info["weights"][name])
            lines = src[name]
            if len(lines) != need:
                errors.append(f"{mid} {name}: {len(lines)} != {need}")
            sc[name] = [{"zh": z, "en": e} for z, e in lines]
        hurt_need = 10 + extra(info["weights"]["hurt"])
        hurt = {}
        for d in DMG:
            need = hurt_need if d == "generic" else 1
            lines = src["hurt"][d]
            if len(lines) != need:
                errors.append(f"{mid} hurt.{d}: {len(lines)} != {need}")
            hurt[d] = [{"zh": z, "en": e} for z, e in lines]
        sc["hurt"] = hurt
        mobs.append({"mob_id": mid, "scenarios": sc})
    return {"batch": "u0297", "mobs": mobs}, errors


def check(data):
    errs = []
    seen = {}
    for mob in data["mobs"]:
        for sname, payload in mob["scenarios"].items():
            groups = payload.items() if sname == "hurt" else [(sname, payload)]
            for g, lines in groups:
                for ln in lines:
                    zh, en = ln["zh"], ln["en"]
                    n = len(zh)
                    if not (6 <= n <= 20):
                        errs.append(f"{mob['mob_id']} zh {n}: {zh}")
                    w = len(en.split())
                    if not (4 <= w <= 14):
                        errs.append(f"{mob['mob_id']} en {w}: {en}")
                    if not re.search(r"[\u4e00-\u9fff]", zh):
                        errs.append(f"{mob['mob_id']} no han: {zh}")
                    key = re.sub(r"[\s，。、！？,.!?]", "", zh)
                    if key in seen:
                        errs.append(f"dup zh: {zh} ({seen[key]} / {mob['mob_id']})")
                    seen[key] = mob["mob_id"]
    return errs


