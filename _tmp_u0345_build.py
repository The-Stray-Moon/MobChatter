plan = json.load(open("data/dialogue/unique_plan.json", encoding="utf-8"))["u0345"]
weights = {m["mob_id"]: m["weights"] for m in plan}
REG = ["walk", "idle", "look_player", "tempted", "collide", "mate", "pickup",
       "target_acquire", "targeting", "melee_attack", "spawn"]

def clamp(x, lo, hi):
    return max(lo, min(hi, x))

out = {"batch": "u0345", "mobs": []}
errors = []
seen = {}
for mob_id, scen in mobs:
    w = weights[mob_id]
    built = {}
    for key in REG:
        base = scen[key]
        extra = clamp(int(round(10 * (w[key] - 1))), 0, 4)
        need = 10 + extra
        if len(base) != need:
            errors.append(f"{mob_id}.{key}: have {len(base)} need {need}")
        built[key] = base
    h = scen["hurt"]
    if len(h["generic"]) != 10:
        errors.append(f"{mob_id}.hurt.generic len {len(h['generic'])}")
    built["hurt"] = h
    out["mobs"].append({"mob_id": mob_id, "scenarios": built})

    for key, val in built.items():
        items = val if isinstance(val, list) else [x for xs in val.values() for x in xs]
        cnt = 0
        for it in items:
            zh, en = it["zh"], it["en"]
            nz = len(zh)
            ne = len(en.split())
            if not (6 <= nz <= 20):
                errors.append(f"{mob_id}.{key} zh len {nz}: {zh}")
            if not (4 <= ne <= 14):
                errors.append(f"{mob_id}.{key} en words {ne}: {en}")
            if zh in seen:
                errors.append(f"dup zh {zh} ({seen[zh]} / {mob_id}.{key})")
            seen[zh] = f"{mob_id}.{key}"
            cnt += 1

os.makedirs("data/dialogue/unique", exist_ok=True)
if errors:
    print("\n".join(errors))
else:
    with open("data/dialogue/unique/u0345.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")
    total = 0
    for m in out["mobs"]:
        for k, v in m["scenarios"].items():
            total += len(v) if isinstance(v, list) else sum(len(x) for x in v.values())
    print("ok", len(out["mobs"]), total)
