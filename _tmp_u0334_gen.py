for mob_id in ["pixelmon:steenee", "pixelmon:stonjourner", "pixelmon:stoutland", "pixelmon:stufful"]:
    info = PLAN_MOBS[mob_id]
    w = info["weights"]
    src = D[mob_id]
    scen = {}
    for name in SCENARIOS:
        want = count_for(w[name])
        lines = src[name]
        if len(lines) != want:
            problems.append(f"{mob_id} {name}: {len(lines)} != {want}")
        if want != 10:
            pass
        scen[name] = [{"zh": z, "en": e} for z, e in lines]
    hurt = {"generic": [{"zh": z, "en": e} for z, e in src["hurt_generic"]]}
